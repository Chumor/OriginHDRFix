#!/usr/bin/env python3

import contextlib
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import prepare_release_metadata
import validate_release_metadata as metadata


ROOT = Path(__file__).resolve().parent.parent


class ReleaseMetadataTests(unittest.TestCase):
    def test_version_bump_needs_no_prepared_changelog_or_update_json(self) -> None:
        with tempfile.TemporaryDirectory(prefix="originhdrfix-release-") as directory:
            root = Path(directory)
            (root / "module").mkdir()
            (root / "update").mkdir()
            module = (ROOT / "module/module.prop").read_text(encoding="utf-8")
            values = metadata.read_module_prop()
            module = module.replace(f"version={values['version']}\n", "version=v2.0.0\n")
            module = module.replace(f"versionCode={values['versionCode']}\n", "versionCode=20\n")
            (root / "module/module.prop").write_text(module, encoding="utf-8")
            history = "## What's Changed in 1.0.0\n\n* Existing release history.\n"
            (root / "update/CHANGELOG.md").write_text("# Changelog\n\n" + history, encoding="utf-8")
            notes = "## What's Changed in 2.0.0\n\n* New HDR support.\n"
            release_notes = notes.replace("New HDR support.", "New HDR support. by @Chumor")
            notes_path = root / "notes.md"
            notes_path.write_text(release_notes, encoding="utf-8")

            with patch.object(metadata, "ROOT", root), contextlib.redirect_stdout(io.StringIO()):
                with patch.object(sys, "argv", ["validate", "--tag", "v2.0.0"]):
                    metadata.main()
                prepare_release_metadata.prepare_release(notes_path)
                with patch.object(sys, "argv", ["validate", "--tag", "v2.0.0", "--check-release"]):
                    metadata.main()

            changelog = (root / "update/CHANGELOG.md").read_text(encoding="utf-8")
            self.assertEqual(changelog, f"# Changelog\n\n{notes}\n{history}")
            self.assertEqual(notes_path.read_text(encoding="utf-8"), release_notes)
            update = json.loads((root / "update/update.json").read_text(encoding="utf-8"))
            self.assertEqual(update["version"], "v2.0.0")
            self.assertEqual(update["versionCode"], 20)
            self.assertTrue(update["zipUrl"].endswith("/v2.0.0/OriginHDRFix-v2.0.0-20.zip"))
            self.assertEqual((root / "module/module.prop").read_text(encoding="utf-8"), module)

            # A second release must retain both earlier entries without regenerating them.
            module = module.replace("version=v2.0.0\n", "version=v2.0.1\n")
            (root / "module/module.prop").write_text(module, encoding="utf-8")
            next_notes = "## What's Changed in 2.0.1\n\n* Fix HDR support.\n"
            notes_path.write_text(next_notes, encoding="utf-8")
            with patch.object(metadata, "ROOT", root):
                prepare_release_metadata.prepare_release(notes_path)
            self.assertEqual(
                (root / "update/CHANGELOG.md").read_text(encoding="utf-8"),
                "# Changelog\n\n" + next_notes + "\n" + changelog.removeprefix("# Changelog\n\n"),
            )

    def test_source_validation_rejects_tag_mismatch(self) -> None:
        with patch.object(sys, "argv", ["validate", "--tag", "v999.0.0"]):
            with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit) as result:
                metadata.main()
            self.assertEqual(result.exception.code, 1)

    def test_changelog_omits_github_credits_and_preserves_changes_and_compare_link(self) -> None:
        notes = (
            "## What's Changed in 1.0.1\n\n"
            "* fix: restore HDR by @Chumor\n"
            "* chore(deps): update library by @renovate[bot] in [#12](https://github.com/example/repo/pull/12)\n"
            "* fix: support @mentions in app names by @another-author\n"
            "* docs: explain setup in [#13](https://github.com/example/repo/pull/13)\n\n"
            "### New Contributors\n"
            "* @another-author made their first contribution in [#14](https://github.com/example/repo/pull/14)\n\n"
            "**Full Changelog**: [v1.0.0...v1.0.1](https://github.com/example/repo/compare/v1.0.0...v1.0.1)\n\n"
            "<!-- generated by git-cliff -->\n"
        )
        expected = (
            "## What's Changed in 1.0.1\n\n"
            "* fix: restore HDR\n"
            "* chore(deps): update library\n"
            "* fix: support @mentions in app names\n"
            "* docs: explain setup\n\n"
            "**Full Changelog**: [v1.0.0...v1.0.1](https://github.com/example/repo/compare/v1.0.0...v1.0.1)\n\n"
            "<!-- generated by git-cliff -->\n"
        )
        self.assertEqual(prepare_release_metadata.changelog_notes(notes), expected)
        self.assertEqual(prepare_release_metadata.changelog_notes(expected), expected)


if __name__ == "__main__":
    unittest.main()
